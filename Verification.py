import pandas as pd
from google.colab import files
from IPython.display import display

print("STEP 1: Select Vaskar_results.csv only")
csv_upload = files.upload()
csv_files = [name for name in csv_upload if name.lower().endswith(".csv")]
assert len(csv_files) == 1, "Please upload exactly one CSV: results(1).csv"
csv_name = csv_files[0]
results = pd.read_csv(csv_name)
assert {"date", "home_team", "away_team", "home_score", "away_score"}.issubset(results.columns), "CSV missing required international-results columns"
print("Loaded independent results:", csv_name, "| Rows:", len(results))

print("STEP 2: Select Vaskar_World_Cup_2026_Regression_2_1.xlsx only")
xlsx_upload = files.upload()
xlsx_files = [name for name in xlsx_upload if name.lower().endswith(".xlsx")]
assert len(xlsx_files) == 1, "Please upload exactly one Excel workbook (.xlsx)"
xlsx_name = xlsx_files[0]
history = pd.read_excel(xlsx_name, sheet_name="Initial_5_History")
wc = pd.read_excel(xlsx_name, sheet_name="Regression_2.1")
results["date"] = pd.to_datetime(results["date"])
wc["Date"] = pd.to_datetime(wc["Date"])
print("Independent results through:", results["date"].max().date())
print("History teams:", len(history), "| World Cup rows:", len(wc))
assert len(history) == 48 and len(wc) == 104, "Expected 48 teams and 104 World Cup matches"

# Match-score comparison. The team score is written first even when the team played away.
records=[]
for _, row in history.iterrows():
    team=row['Team']
    games=wc[(wc['Team_A']==team)|(wc['Team_B']==team)]
    if games.empty:
        raise ValueError(f'Team missing from World Cup data: {team}')
    cutoff=games['Date'].min()
    eligible=results[(results['date']<cutoff)&((results['home_team']==team)|(results['away_team']==team))]
    # Keep original CSV order for matches sharing a date; do not infer an intra-day sequence.
    latest=eligible.sort_values('date',kind='stable').tail(5)
    original=[str(row[c]).strip() for c in ['Oldest→Newest score 1','Score 2','Score 3','Score 4','Score 5']]
    independent=[]; details=[]
    for _,g in latest.iterrows():
        home=(g['home_team']==team)
        gf=int(g['home_score'] if home else g['away_score'])
        ga=int(g['away_score'] if home else g['home_score'])
        opponent=g['away_team'] if home else g['home_team']
        independent.append(f'{gf}-{ga}')
        details.append(f"{g['date'].date()} vs {opponent} ({g['tournament']}): {gf}-{ga}")
    status='MATCH' if len(independent)==5 and original==independent else ('INSUFFICIENT SOURCE MATCHES' if len(independent)<5 else 'MISMATCH')
    records.append({'Team':team,'First_WC_Match':cutoff.date().isoformat(),
      'Original_5':', '.join(original),'Independent_5':', '.join(independent),
      'Status':status,'Match_Details':' | '.join(details)})
comparison=pd.DataFrame(records)
print(comparison['Status'].value_counts().to_string())
display(comparison[['Team','Original_5','Independent_5','Status']])
print('Teams needing review:')
display(comparison.loc[comparison.Status!='MATCH'])

